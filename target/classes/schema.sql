DROP TABLE IF EXISTS order_allocations;
DROP TABLE IF EXISTS arrival_histories;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS coils;
DROP TABLE IF EXISTS steel_sheets;
DROP TABLE IF EXISTS users;

-- 1. ユーザーマスタ
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL -- ROLE_SALES, ROLE_WAREHOUSE, ROLE_ADMIN
);

-- 2. 鋼板マスタ
CREATE TABLE steel_sheets (
    steel_sheet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steel_code VARCHAR(30) NOT NULL UNIQUE,
    steel_name VARCHAR(100) NOT NULL,
    steel_grade VARCHAR(30) NOT NULL,
    usage_category VARCHAR(50) NOT NULL,
    thickness DECIMAL(4, 2) NOT NULL,
    width INTEGER NOT NULL,
    safety_stock_weight INTEGER NOT NULL DEFAULT 10000
);

-- 3. コイル在庫テーブル
CREATE TABLE coils (
    coil_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coil_number VARCHAR(30) NOT NULL UNIQUE,
    steel_sheet_id BIGINT NOT NULL,
    initial_weight INTEGER NOT NULL,
    physical_weight INTEGER NOT NULL,
    available_weight INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL, -- AVAILABLE, PARTIALLY_ALLOCATED, FULLY_ALLOCATED, DEPLETED
    arrival_date DATE NOT NULL,
    version INTEGER NOT NULL DEFAULT 0, -- 楽観的ロック用
    CONSTRAINT fk_coils_steel_sheet FOREIGN KEY (steel_sheet_id) REFERENCES steel_sheets(steel_sheet_id)
);

-- 4. 注文テーブル
CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(30) NOT NULL UNIQUE,
    customer_name VARCHAR(100) NOT NULL,
    steel_sheet_id BIGINT NOT NULL,
    order_weight INTEGER NOT NULL,
    allocated_weight INTEGER NOT NULL DEFAULT 0,
    desired_delivery_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL, -- ALLOCATED, BACKORDERED, SHIPPED, CANCELED
    ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    shipped_at TIMESTAMP,
    CONSTRAINT fk_orders_steel_sheet FOREIGN KEY (steel_sheet_id) REFERENCES steel_sheets(steel_sheet_id)
);

-- 5. 引当明細テーブル（注文とコイルの中間テーブル）
CREATE TABLE order_allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    coil_id BIGINT NOT NULL,
    allocated_weight INTEGER NOT NULL,
    allocated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alloc_order FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT fk_alloc_coil FOREIGN KEY (coil_id) REFERENCES coils(coil_id)
);

-- 6. 入荷履歴テーブル
CREATE TABLE arrival_histories (
    arrival_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coil_id BIGINT NOT NULL,
    steel_sheet_id BIGINT NOT NULL,
    arrival_weight INTEGER NOT NULL,
    arrival_date DATE NOT NULL,
    auto_allocated_info VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_arrival_coil FOREIGN KEY (coil_id) REFERENCES coils(coil_id),
    CONSTRAINT fk_arrival_steel_sheet FOREIGN KEY (steel_sheet_id) REFERENCES steel_sheets(steel_sheet_id)
);

-- 検索パフォーマンス向上のためのインデックス
CREATE INDEX idx_coils_steel_status ON coils(steel_sheet_id, status, arrival_date);
CREATE INDEX idx_orders_steel_status ON orders(steel_sheet_id, status, ordered_at);

